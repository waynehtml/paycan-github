CREATE   PROCEDURE [paycan_restricted_curated].[SP_MERGE_LYNX_PAYMENT]
AS
BEGIN

MERGE [paycan_restricted_curated].[LYNX_PAYMENT] AS [Target]          
USING [paycan_restricted_standardized].[LYNX_PAYMENT] AS [Source]           
    ON	[Target].[LYNX_PAYMENT_ID]	= [Source].[LYNX_PAYMENT_ID] and
		[Target].[BATCH_ID]			= [Source].[BATCH_ID]
WHEN MATCHED THEN
  UPDATE SET 
	[Target].[VALIDATION_STATUS]			=	[Source].[VALIDATION_STATUS], 
	[Target].[PAYMENT_ID]					=	[Source].[PAYMENT_ID], 
	[Target].[SYSTEM_REFERENCE]				=	[Source].[SYSTEM_REFERENCE], 
	[Target].[CYCLE_DATE]					=	[Source].[CYCLE_DATE], 
	[Target].[PAYER_INSTITUTION_NUMBER]		=	[Source].[PAYER_INSTITUTION_NUMBER], 
	[Target].[PAYER_INSTITUTION_IRN]		=	[Source].[PAYER_INSTITUTION_IRN], 
	[Target].[PAYER_INSTITUTION_NAME]		=	[Source].[PAYER_INSTITUTION_NAME], 
	[Target].[RECEIVER_INSTITUTION_NUMBER]	=	[Source].[RECEIVER_INSTITUTION_NUMBER], 
	[Target].[RECEIVER_INSTITUTION_IRN]		=	[Source].[RECEIVER_INSTITUTION_IRN], 
	[Target].[RECEIVER_INSTITUTION_NAME]	=	[Source].[RECEIVER_INSTITUTION_NAME], 
	[Target].[PAYER_PARTICIPANT_NUMBER]		=	[Source].[PAYER_PARTICIPANT_NUMBER], 
	[Target].[PAYER_PARTICIPANT_BIC]		=	[Source].[PAYER_PARTICIPANT_BIC], 
	[Target].[PAYER_PARTICIPANT_NAME]		=	[Source].[PAYER_PARTICIPANT_NAME], 
	[Target].[RECEIVER_PARTICIPANT_NUMBER]	=	[Source].[RECEIVER_PARTICIPANT_NUMBER], 
	[Target].[RECEIVER_PARTICIPANT_BIC]		=	[Source].[RECEIVER_PARTICIPANT_BIC], 
	[Target].[RECEIVER_PARTICIPANT_NAME]	=	[Source].[RECEIVER_PARTICIPANT_NAME],
	[Target].[PAYER_INSTITUTION]			=	[Source].[PAYER_INSTITUTION], 
	[Target].[PAYER_PARTICIPANT]			=	[Source].[PAYER_PARTICIPANT], 
	[Target].[PAYER_REFERENCE]				=	[Source].[PAYER_REFERENCE], 
	[Target].[SETTLEMENT_MECHANISM_CD]		=	[Source].[SETTLEMENT_MECHANISM_CD], 
	[Target].[RECEIVER_INSTITUTION]			=	[Source].[RECEIVER_INSTITUTION], 
	[Target].[RECEIVER_PARTICIPANT]			=	[Source].[RECEIVER_PARTICIPANT], 
	[Target].[SWIFT_MSG_TYPE_CD]			=	[Source].[SWIFT_MSG_TYPE_CD], 
	[Target].[TRANSACTION_TYPE]				=	[Source].[TRANSACTION_TYPE], 
	[Target].[PCRN]							=	[Source].[PCRN],	 
	[Target].[AMOUNT]						=	[Source].[AMOUNT], 
	[Target].[GRIDLOCK_SETTLED_ID]			=	[Source].[GRIDLOCK_SETTLED_ID], 
	[Target].[PRIORITY]						=	[Source].[PRIORITY], 
	[Target].[LAST_MODIFIED_TS]				=	[Source].[LAST_MODIFIED_TS], 
	[Target].[STATUS_TYPE_CD]				=	[Source].[STATUS_TYPE_CD], 
	[Target].[STATUS_CHANGE_TIME_TS]		=	[Source].[STATUS_CHANGE_TIME_TS], 
	[Target].[STATUS_REASON]				=	[Source].[STATUS_REASON], 
	[Target].[STATUS_MILLISECOND_DURATION]	=	[Source].[STATUS_MILLISECOND_DURATION], 
	[Target].[ingestion_date]				=	[Source].[ingestion_date],
	[Target].[batch_date]					=	[Source].[batch_date]
WHEN NOT MATCHED THEN 
	INSERT
	(
		[LYNX_PAYMENT_ID], 
		[BATCH_ID], 
		[VALIDATION_STATUS], 
		[PAYMENT_ID], 
		[SYSTEM_REFERENCE], 
		[CYCLE_DATE], 
		[PAYER_INSTITUTION_NUMBER], 
		[PAYER_INSTITUTION_IRN], 
		[PAYER_INSTITUTION_NAME], 
		[RECEIVER_INSTITUTION_NUMBER], 
		[RECEIVER_INSTITUTION_IRN], 
		[RECEIVER_INSTITUTION_NAME], 
		[PAYER_PARTICIPANT_NUMBER], 
		[PAYER_PARTICIPANT_BIC], 
		[PAYER_PARTICIPANT_NAME], 
		[RECEIVER_PARTICIPANT_NUMBER], 
		[RECEIVER_PARTICIPANT_BIC], 
		[RECEIVER_PARTICIPANT_NAME],
		[PAYER_INSTITUTION], 
		[PAYER_PARTICIPANT], 
		[PAYER_REFERENCE], 
		[SETTLEMENT_MECHANISM_CD], 
		[RECEIVER_INSTITUTION], 
		[RECEIVER_PARTICIPANT], 
		[SWIFT_MSG_TYPE_CD], 
		[TRANSACTION_TYPE], 
		[PCRN], 
		[AMOUNT], 
		[GRIDLOCK_SETTLED_ID], 
		[PRIORITY], 
		[LAST_MODIFIED_TS], 
		[STATUS_TYPE_CD], 
		[STATUS_CHANGE_TIME_TS], 
		[STATUS_REASON], 
		[STATUS_MILLISECOND_DURATION], 
		[ingestion_date],
		[batch_date]
	)
	VALUES
	(
		[Source].[LYNX_PAYMENT_ID], 
		[Source].[BATCH_ID], 
		[Source].[VALIDATION_STATUS], 
		[Source].[PAYMENT_ID], 
		[Source].[SYSTEM_REFERENCE], 
		[Source].[CYCLE_DATE], 
		[Source].[PAYER_INSTITUTION_NUMBER], 
		[Source].[PAYER_INSTITUTION_IRN], 
		[Source].[PAYER_INSTITUTION_NAME], 
		[Source].[RECEIVER_INSTITUTION_NUMBER], 
		[Source].[RECEIVER_INSTITUTION_IRN], 
		[Source].[RECEIVER_INSTITUTION_NAME], 
		[Source].[PAYER_PARTICIPANT_NUMBER], 
		[Source].[PAYER_PARTICIPANT_BIC], 
		[Source].[PAYER_PARTICIPANT_NAME], 
		[Source].[RECEIVER_PARTICIPANT_NUMBER], 
		[Source].[RECEIVER_PARTICIPANT_BIC], 
		[Source].[RECEIVER_PARTICIPANT_NAME],
		[Source].[PAYER_INSTITUTION], 
		[Source].[PAYER_PARTICIPANT], 
		[Source].[PAYER_REFERENCE], 
		[Source].[SETTLEMENT_MECHANISM_CD], 
		[Source].[RECEIVER_INSTITUTION], 
		[Source].[RECEIVER_PARTICIPANT], 
		[Source].[SWIFT_MSG_TYPE_CD], 
		[Source].[TRANSACTION_TYPE], 
		[Source].[PCRN], 
		[Source].[AMOUNT], 
		[Source].[GRIDLOCK_SETTLED_ID], 
		[Source].[PRIORITY], 
		[Source].[LAST_MODIFIED_TS], 
		[Source].[STATUS_TYPE_CD], 
		[Source].[STATUS_CHANGE_TIME_TS], 
		[Source].[STATUS_REASON], 
		[Source].[STATUS_MILLISECOND_DURATION], 
		[Source].[ingestion_date],
		[Source].[batch_date]
	);

END