CREATE   PROCEDURE [paycan_restricted_curated].[SP_MERGE_LYNX_PAYMENT_SUMMARY]
AS
BEGIN

MERGE [paycan_restricted_curated].[LYNX_PAYMENT_SUMMARY] AS [Target]          
USING [paycan_restricted_standardized].[LYNX_PAYMENT_SUMMARY] AS [Source]           
    ON	[Target].[PAYMENT_ID]	= [Source].[PAYMENT_ID] and
		[Target].[BATCH_ID]			= [Source].[BATCH_ID]
WHEN MATCHED THEN
  UPDATE SET 
	[Target].[PAYER_REFERENCE]			=	[Source].[PAYER_REFERENCE], 
	[Target].[SYSTEM_REFERENCE]			=	[Source].[SYSTEM_REFERENCE], 
	[Target].[CYCLE_DATE]				=	[Source].[CYCLE_DATE], 
	[Target].[PAYER_INSTITUTION]		=	[Source].[PAYER_INSTITUTION], 
	[Target].[PAYER_PARTICIPANT]		=	[Source].[PAYER_PARTICIPANT], 
	[Target].[SETTLEMENT_MECHANISM_CD]	=	[Source].[SETTLEMENT_MECHANISM_CD], 
	[Target].[RECEIVER_INSTITUTION]		=	[Source].[RECEIVER_INSTITUTION], 
	[Target].[RECEIVER_PARTICIPANT]		=	[Source].[RECEIVER_PARTICIPANT], 
	[Target].[SWIFT_MSG_TYPE_CD]		=	[Source].[SWIFT_MSG_TYPE_CD], 
	[Target].[TRANSACTION_TYPE]			=	[Source].[TRANSACTION_TYPE], 
	[Target].[AMOUNT]					=	[Source].[AMOUNT], 
	[Target].[GRIDLOCK_SETTLED_ID]		=	[Source].[GRIDLOCK_SETTLED_ID],
	[Target].[PRIORITY]					=	[Source].[PRIORITY],
	[Target].[REGISTERED]				=	[Source].[REGISTERED], 
	[Target].[SETTLED]					=	[Source].[SETTLED],
	[Target].[QUEUED]					=	[Source].[QUEUED],
	[Target].[DIARISED]					=	[Source].[DIARISED], 
	[Target].[REMOVED]					=	[Source].[REMOVED],
	[Target].[REPRIORITISE]				=	[Source].[REPRIORITISE],
	[Target].[DISCARDED]				=	[Source].[DISCARDED],
	[Target].[RESEQUENCED]				=	[Source].[RESEQUENCED],
	[Target].[INSUFFUNDS]				=	[Source].[INSUFFUNDS],
	[Target].[REGISTERED_TIME]			=	[Source].[REGISTERED_TIME], 
	[Target].[SETTLED_TIME]				=	[Source].[SETTLED_TIME],
	[Target].[QUEUED_TIME]				=	[Source].[QUEUED_TIME], 
	[Target].[DIARISED_TIME]			=	[Source].[DIARISED_TIME], 
	[Target].[REMOVED_TIME]				=	[Source].[REMOVED_TIME], 
	[Target].[REPRIORITISE_TIME]		=	[Source].[REPRIORITISE_TIME], 
	[Target].[DISCARDED_TIME]			=	[Source].[DISCARDED_TIME], 
	[Target].[RESEQUENCED_TIME]			=	[Source].[RESEQUENCED_TIME], 
	[Target].[INSUFFUNDS_TIME]			=	[Source].[INSUFFUNDS_TIME], 
	[Target].[ingestion_date]			=	[Source].[ingestion_date],
	[Target].[batch_date]				=	[Source].[batch_date]
WHEN NOT MATCHED THEN 
	INSERT
	(		
		[BATCH_ID], 
		[PAYMENT_ID], 
		[PAYER_REFERENCE], 
		[SYSTEM_REFERENCE], 
		[CYCLE_DATE], 
		[PAYER_INSTITUTION], 
		[PAYER_PARTICIPANT], 
		[SETTLEMENT_MECHANISM_CD], 
		[RECEIVER_INSTITUTION], 
		[RECEIVER_PARTICIPANT], 
		[SWIFT_MSG_TYPE_CD], 
		[TRANSACTION_TYPE], 
		[AMOUNT], 
		[GRIDLOCK_SETTLED_ID],
		[PRIORITY],
		[REGISTERED], 
		[SETTLED],
		[QUEUED],
		[DIARISED], 
		[REMOVED],
		[REPRIORITISE],
		[DISCARDED],
		[RESEQUENCED],
		[INSUFFUNDS],
		[REGISTERED_TIME], 
		[SETTLED_TIME],
		[QUEUED_TIME], 
		[DIARISED_TIME], 
		[REMOVED_TIME], 
		[REPRIORITISE_TIME], 
		[DISCARDED_TIME], 
		[RESEQUENCED_TIME], 
		[INSUFFUNDS_TIME], 
		[ingestion_date],
		[batch_date]
	)
	VALUES
	(
		[Source].[BATCH_ID], 
		[Source].[PAYMENT_ID], 
		[Source].[PAYER_REFERENCE], 
		[Source].[SYSTEM_REFERENCE], 
		[Source].[CYCLE_DATE], 
		[Source].[PAYER_INSTITUTION], 
		[Source].[PAYER_PARTICIPANT], 
		[Source].[SETTLEMENT_MECHANISM_CD], 
		[Source].[RECEIVER_INSTITUTION], 
		[Source].[RECEIVER_PARTICIPANT], 
		[Source].[SWIFT_MSG_TYPE_CD], 
		[Source].[TRANSACTION_TYPE], 
		[Source].[AMOUNT], 
		[Source].[GRIDLOCK_SETTLED_ID],
		[Source].[PRIORITY],
		[Source].[REGISTERED], 
		[Source].[SETTLED],
		[Source].[QUEUED],
		[Source].[DIARISED], 
		[Source].[REMOVED],
		[Source].[REPRIORITISE],
		[Source].[DISCARDED],
		[Source].[RESEQUENCED],
		[Source].[INSUFFUNDS],
		[Source].[REGISTERED_TIME], 
		[Source].[SETTLED_TIME],
		[Source].[QUEUED_TIME], 
		[Source].[DIARISED_TIME], 
		[Source].[REMOVED_TIME], 
		[Source].[REPRIORITISE_TIME], 
		[Source].[DISCARDED_TIME], 
		[Source].[RESEQUENCED_TIME], 
		[Source].[INSUFFUNDS_TIME], 
		[Source].[ingestion_date],
		[Source].[batch_date]
	);

END